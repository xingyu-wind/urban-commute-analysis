"""Local regression on NEW scoped schemas in this task's freshly installed demo MySQL.

Only decrypts credentials generated by FIRST-SETUP in the named test installation.
No existing project/production credentials, databases or users are accessed.
"""
import argparse
import importlib.util
import json
import os
from pathlib import Path
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]

def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--installation',type=Path,required=True)
    p.add_argument('--output',type=Path,required=True)
    p.add_argument('--suites',nargs='+',default=['core','security','etl','python'])
    args=p.parse_args(); installed=args.installation.resolve();out=args.output.resolve();out.mkdir(parents=True,exist_ok=False)
    if not installed.is_relative_to(ROOT/'dist') or 'ui-' not in installed.name:
        raise RuntimeError('Only a task-owned ui-* installation inside dist is permitted')
    identity=json.loads((installed/'BUILD.json').read_text(encoding='utf-8'))
    assert identity['offline'] and identity['applicationSource'] != '97f30db15a5292c0be9a0103359ccc7e97f5ddfa'
    module_spec=importlib.util.spec_from_file_location('task_owned_installation',installed/'launcher/portable.py')
    module=importlib.util.module_from_spec(module_spec);module_spec.loader.exec_module(module)
    config=module.read(installed/'state/instance.json');assert config['initialized']
    env=dict(os.environ,URBAN_COMMUTE_NO_PAUSE='1',NO_PROXY='127.0.0.1,localhost,::1',CONTRACT_PYTHON=sys.executable)
    checks=[];passed=False;failures=[]
    def run(label,command,environment=env):
        with (out/(label+'.log')).open('xb') as log:
            r=subprocess.run(command,cwd=ROOT,env=environment,stdout=log,stderr=subprocess.STDOUT)
        checks.append(dict(check=label,exitCode=r.returncode));print(label+' exit='+str(r.returncode),flush=True)
        if r.returncode:raise RuntimeError(label+' failed; inspect task log')
    try:
        run('start',['cmd','/c',str(installed/'START.bat'),'-NoBrowser'])
        # Validate the exact owned database before forwarding its generated root account to provisioning.
        secret=module.credentials()
        with module.sql(config,secret,'',root=True) as connection:
            with connection.cursor() as c:
                c.execute('SELECT @@server_uuid,@@datadir');uuid,directory=c.fetchone()
                assert uuid==config['serverUuid'] and Path(directory).resolve()==(module.mysql_home()/'data').resolve()
        env.update(S3_MYSQL_HOST='127.0.0.1',S3_MYSQL_PORT=str(config['dbPort']),S3_ADMIN_USER='root',S3_ADMIN_PASSWORD=secret['rootPassword'],MYSQL_CLIENT=str(module.runtime('mysql').parent/'mysql.exe'))
        definitions={
            'core':['scripts/s4_checks.py','--with-core'],
            'security':['scripts/s8_checks.py'],
            'etl':['scripts/s5_checks.py'],
            'warehouse-admission':['scripts/s6_checks.py','--admission-only'],
            'model':['scripts/s7_checks.py'],
        }
        for suite in args.suites:
          try:
            if suite=='layout':
                run('layout',['node','frontend/scripts/verify-built-workbench.mjs',str(out/'layout'),'http://127.0.0.1:'+str(config['webPort'])]);continue
            if suite=='metadata':
                run('metadata',[sys.executable,'scripts/s3_database.py','--output',str(out/'metadata-database.json'),'--','cmd','/c','backend\\mvnw.cmd','-f','backend/pom.xml','-B','-ntp','-Dtest=AvailabilityControllerTest,TrafficIntegrationTest,PredictionIntegrationTest','verify']);continue
            if suite=='python':
                run('python',[sys.executable,'-m','pytest','ml/tests','-q','--junitxml='+str(out/'python.xml')]);continue
            if suite not in definitions:raise ValueError('Unknown suite')
            run(suite,[sys.executable,'scripts/s3_database.py','--output',str(out/(suite+'-database.json')),'--',sys.executable,*definitions[suite],'--output',str(out/suite)])
          except RuntimeError as error:
            failures.append(str(error))
        if failures:raise RuntimeError('; '.join(failures))
        passed=True
    finally:
        try:run('stop',['cmd','/c',str(installed/'STOP.bat')])
        finally:(out/'summary.json').write_text(json.dumps(dict(passed=passed,taskOwnedDatabase=True,newScopedSchemas=True,noExistingCredentials=True,checks=checks,failures=failures),indent=2)+'\n',encoding='utf-8')

if __name__=='__main__':main()
